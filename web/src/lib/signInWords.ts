export const errorWords = (t: Translate): SignInErrorText =>
  Object.fromEntries(Object.entries(ERRORS).map(([code, key]) => [code, t(key)]))

export const arrivedWords = (t: Translate): Record<string, string> =>
  Object.fromEntries(Object.entries(ARRIVED).map(([code, key]) => [code, t(key)]))

/** A code a sign-in service sent the browser back with, in words. */
export function arrivedText(t: Translate, code: string): string {
  const key = (ARRIVED as Partial<Record<string, TranslationKey>>)[code] ?? (ERRORS as Partial<Record<string, TranslationKey>>)[code]
  return t(key ?? 'login.failed')
}

// GlimStone fills in {min} where ArrowLoop's sentence, written count-neutral, says {count}.
const shortHint = (t: Translate) => t('password.longerIsSafer', { count: '{min}' })
const counted = (t: Translate, key: TranslationKey) => ({ other: t(key, { count: '{count}' }) })

