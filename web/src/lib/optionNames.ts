/** Where one backend means something else by an option than the others do. */
const BY_BACKEND: Record<string, TranslationKey> = {
  'ftp.concurrency': 'opt.connections',
  'oracleobjectstorage.provider': 'opt.authProvider',
  'seafile.2fa': 'opt.seafileTwoFactor',
  'storj.provider': 'opt.signInMethod',
  'tardigrade.provider': 'opt.signInMethod',
}

/** The label for one option: its translation where there is one, its rclone name otherwise. */
export function optionLabel(name: string, t: (key: TranslationKey) => string, backend?: string): string {
  const key = BY_BACKEND[`${backend}.${name}`] ?? NAMES[name]
  return key ? t(key) : name
}

/** Whether this option has a translated name at all. */
export function hasOptionLabel(name: string): boolean {
  return NAMES[name] !== undefined
}
