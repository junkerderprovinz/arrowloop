def _drop_plate(root, source, slug):
    """Remove the rectangle the rest of the mark is sitting on.

    A brand asset is often drawn on a plate, which in a list of logos makes it
    the one mark arriving in its own box. A plate is the first thing drawn, a
    rectangle, with everything else inside it; it need not fill the canvas
    (Linkbox's plate covers a fifth of a 367x70 canvas whose text was lost on
    export). A white mark left invisible on a light page is handled by
    FORCE_THEMED. Returns the plate's colour, which a mark painting only white
    lights its tile up in.
    """
    if svgelements is None:
        raise SystemExit("the plate rule needs svgelements (pip install svgelements)")
    try:
        drawing = svgelements.SVG.parse(str(source))
    except Exception:
        return

    boxes = []
    for element in drawing.elements():
        if not isinstance(element, svgelements.Shape):
            continue
        try:
            bounds = element.bbox()
        except Exception:
            continue
        if bounds:
            boxes.append((type(element).__name__, bounds))
    if len(boxes) < 2 or boxes[0][0] != "Rect":
        return

    plate = boxes[0][1]
    rest = boxes[1:]
    # Half a unit of tolerance for drawing-program rounding.
    covers = (
        plate[0] <= min(b[0] for _, b in rest) + 0.5
        and plate[1] <= min(b[1] for _, b in rest) + 0.5
        and plate[2] >= max(b[2] for _, b in rest) - 0.5
        and plate[3] >= max(b[3] for _, b in rest) - 0.5
    )
    if not covers:
        return

