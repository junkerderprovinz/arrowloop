"""Generate the provider marks from Simple Icons.

    npm install simple-icons@16 somewhere, then:
    python scripts/gen_brand_glyphs.py <path to simple-icons/icons>

Simple Icons is CC0, so a mark taken from it carries no attribution duty. The
trademarks themselves remain their owners': every mark here is used to NAME the
service it belongs to, on a row that connects to exactly that service, which is
the one use of a trademark that needs no permission. Each is reproduced
unmodified apart from being given `currentColor`, and nothing about any of them
claims endorsement or affiliation.

Generated rather than transcribed for the same reason every other generator in
this repo exists: twenty-five hand-copied paths drift from their source the
first time one is touched, and a wrong brand mark is worse than none.

WRITES web/src/components/brandGlyphs.tsx, which also holds the GitHub mark that
was added by hand before this script existed - so the file is regenerated whole
and the GitHub entry is part of the table below rather than being preserved.
"""
