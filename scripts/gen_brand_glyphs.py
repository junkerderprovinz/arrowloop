# Every mark's own INK, measured, for marks whose drawing does not fill the box
# it was saved in.
#
# The eye compares a glyph's ink, not its viewBox, and imported artwork varies
# wildly in how much of its own box it uses: measured across the running list,
# the painted extent ran from 32px to 64px, a factor of two, on marks that are
# all in identically sized boxes. jdp, looking at it: "die logos sind stark
# unterschiedlich gross." Cropping the box to the drawing is what makes them
# agree, and it is the same fix the sibling app arrived at after five rounds of
# the same report.
#
# A second thing it fixes: a logo exported with its wordmark as live TEXT loses
# the text and keeps the box, so the symbol ends up in a corner of a mostly
# empty rectangle. Linkbox looked like a 5.3:1 wordmark 8 pixels tall and its
# ink is square.
#
# NO LONGER HAND-KEPT. This used to be a table of boxes read off getBBox() in
# the running app, and it had the defect every such table has: it was right for
# the marks somebody had looked at and silent about the rest. Synology sat in a
# box 3.90 times taller than its own drawing for as long as the list existed,
# which is why a wordmark that fills its line rendered six pixels tall. Nobody
# was going to notice by reading a list of twenty-eight names.
#
# `crop_to_ink` below now measures every mark instead, off the FINAL markup -
# after the plate is dropped, after the styles are folded in - and the
# measurement reproduced twenty-six of these boxes to the last decimal, which
# is what earned it the job. The dict stays as an OVERRIDE for a mark the
# measurement gets wrong, and `crop_to_ink` refuses an entry that merely
# restates what it measured: a hand value that agrees with the measurement is
# not a safety net, it is a second copy to keep in step.
#
# It no longer feeds the emitted box or the plate rule. It used to do both, and
# that coupling was a trap: the plate rule recognises a rectangle by it being
# full-bleed, so handing it a box already cropped to the ink makes every plate
# invisible to it. Both now read the SOURCE canvas and the cropping happens
# afterwards, on the finished markup.
# EMPTY, and that is the result rather than an omission. Twenty-eight entries
# stood here; the measurement reproduced twenty-six of them to the last
# decimal, and the two it disagreed with - OpenDrive and Linkbox - were not
# measured boxes at all but the source file's own loose rectangle. Linkbox's
# said 68.4 wide where the drawing is 34.7, which is the very defect this table
# was written to fix, sitting inside the fix.
INK = {}

# How much of its box a mark may waste before it is cropped. Two percent is
# below what any eye resolves and above the rounding in these files, so it
# separates "this box is the drawing" from "this box has room in it".
SLACK = 1.02

# Overrides the measurement makes unnecessary, collected across the whole run
# and refused together at the end. One at a time would mean twenty-eight runs
# to clear twenty-eight entries.
REDUNDANT = []


def _measure_ink(component, name):
    """The box the mark actually PAINTS in, in its own viewBox units.

    Measured off the finished markup rather than the source file, because by
    this point three things have already changed the drawing: a full-bleed
    plate may have been dropped, an Illustrator `<style>` block has been folded
    into the elements, and the ids have been prefixed. Measuring earlier would
    describe a mark nobody ships.

    `<defs>`, `<mask>` and `<clipPath>` are cut out first, for the same reason
    their colours are not counted as ink: what is in them is a recipe, not a
    drawing, and a full-canvas mask rectangle would report the whole box as
    painted - which is exactly what Quatrix carries two of.
    """
    if svgelements is None:
        raise SystemExit(
            "crop_to_ink needs the svgelements package (pip install svgelements).\n"
            "It is what measures where each mark actually paints; without it the\n"
            "boxes would go back to being a hand-kept list."
        )
    markup = component[component.index("<svg"):component.rindex("</svg>") + 6]
    markup = markup.replace(" aria-hidden {...props}", " ").replace("{...props}", " ")

    # JSX spellings back to SVG's own. Only the ones these files carry: an
    # unknown attribute would be ignored by the parser and could take a whole
    # shape's geometry with it.
    def style(match):
        pairs = re.findall(r'(\w+):\s*"([^"]*)"', match.group(1))
        return 'style="%s"' % ";".join(
            "%s:%s" % (re.sub(r"(?<!^)(?=[A-Z])", "-", key).lower(), value)
            for key, value in pairs
        )

    markup = re.sub(r"style=\{\{([^}]*)\}\}", style, markup)
    for jsx, svg in (
        ("fillRule", "fill-rule"), ("fillOpacity", "fill-opacity"),
        ("clipPath", "clip-path"), ("clipRule", "clip-rule"),
        ("strokeWidth", "stroke-width"), ("strokeLinecap", "stroke-linecap"),
        ("strokeLinejoin", "stroke-linejoin"), ("strokeMiterlimit", "stroke-miterlimit"),
        ("stopColor", "stop-color"), ("stopOpacity", "stop-opacity"),
        ("xlinkHref", "xlink:href"), ("fillOpacity", "fill-opacity"),
    ):
        markup = markup.replace(jsx + "=", svg + "=")
    for tag in ("defs", "mask", "clipPath"):
        markup = re.sub(r"<%s\b.*?</%s>" % (tag, tag), "", markup, flags=re.S)

    box = [float(v) for v in re.search(r'viewBox="([^"]+)"', markup).group(1).replace(",", " ").split()]
    # `width="1em"` is what the interface wants and what the parser cannot
    # resolve - it raises rather than guessing. Handing it the viewBox's own
    # size makes the viewport transform the identity, so the numbers that come
    # back are already in the units the box is written in.
    markup = re.sub(r'\swidth="[^"]*"', "", markup, count=1)
    markup = re.sub(r'\sheight="[^"]*"', "", markup, count=1)
    markup = markup.replace(
        "<svg ",
        '<svg xmlns="http://www.w3.org/2000/svg" width="%g" height="%g" ' % (box[2], box[3]),
        1,
    )

    handle, path = tempfile.mkstemp(suffix=".svg")
    os.close(handle)
    try:
        io.open(path, "w", encoding="utf-8").write(markup)
        drawing = svgelements.SVG.parse(path)
    finally:
        os.unlink(path)

    left = top = float("inf")
    right = bottom = float("-inf")
    for element in drawing.elements():
        if not isinstance(element, svgelements.Shape):
            continue
        try:
            # WITH the stroke, and that word is the whole difference for a mark
            # drawn as an outline. Oracle Cloud is a stadium in `fill="none"`
            # with a 4-unit stroke: the path runs 2..30 across a 32-wide
            # canvas, and the two units either side ARE the drawing. Measuring
            # the path alone cropped the box onto the centreline and sliced
            # half the outline off all four edges. jdp: "das oracle logo passt
            # nicht."
            bounds = element.bbox(with_stroke=True)
        except Exception:
            continue
        if not bounds:
            continue
        left, top = min(left, bounds[0]), min(top, bounds[1])
        right, bottom = max(right, bounds[2]), max(bottom, bounds[3])
    if right <= left or bottom <= top:
        raise SystemExit("%s paints nothing this can measure" % name)
    # Back into the box's own coordinates: the parse put its origin at 0,0.
    return box, (left + box[0], top + box[1], right - left, bottom - top)


def crop_to_ink(component, name):
    """Tighten a mark's viewBox onto its drawing.

    The eye compares a glyph's INK, not its viewBox, and a tile scales a mark
    to fit - so a drawing in a box twice its height arrives at half the size of
    its neighbours, having asked for the same space and used a quarter of it.
    """
    declared, ink = _measure_ink(component, name)
    slack_x = declared[2] / ink[2]
    slack_y = declared[3] / ink[3]
    # `or 0.0` collapses a measured -0.0 onto 0, because -0.0 is falsy: a
    # bezier that touches the axis lands either side of zero depending on
    # rounding, and "-0" in a viewBox is a diff nobody caused.
    tight = "%s %s %s %s" % tuple(
        (("%.2f" % (round(value, 2) or 0.0)).rstrip("0").rstrip(".") or "0") for value in ink
    )

    if name in INK:
        # An override that agrees with the measurement is dead weight, and dead
        # weight in a table like this is what makes the next person believe the
        # table is doing the work.
        if slack_x <= SLACK and slack_y <= SLACK:
            REDUNDANT.append((name, INK[name], tight))
        else:
            # An override that DISAGREES is the one worth keeping, and worth
            # saying out loud: it is a decision somebody made against the
            # measurement, and silence would make it look like agreement.
            print("  %s: kept its override %s over the measured %s"
                  % (name, INK[name], tight))
        return component

    if slack_x <= SLACK and slack_y <= SLACK:
        return component
    print("  %s: cropped to its ink (%.2fx wide, %.2fx tall)" % (name, slack_x, slack_y))
    cropped, hits = re.subn(r'viewBox="[^"]*"', 'viewBox="%s"' % tight, component, count=1)
    # A replacement that does not land is the worst outcome here, because the
    # line above has already announced the crop: the report would say the mark
    # was fixed and the file would carry the old box. Matching the viewBox by
    # pattern rather than by rebuilding its text avoids the whole class - the
    # numbers come back out of a float and would not round-trip.
    if hits != 1:
        raise SystemExit("%s: could not find its viewBox to crop" % name)
    return cropped


def _inline_css(root, slug):
    """Fold an Illustrator `<style>` block into the elements it paints.

    These files carry their colours as `.st0 { fill: … }` rules in a `<style>`
    element. Keeping that would be the id-collision bug again and worse: class
    names are GLOBAL to the document, so two marks both defining `.st0` would
    have one wearing the other's fill, and unlike ids there is nothing local
    about them to prefix away safely. Dissolving the rules into the elements
    makes each component self-contained, which is what a component should be.

    Runs before the JSX pass on purpose, so a `url(#…)` inside a rule is
    renamed by the same id-prefixing as every other reference.
    """
    parents = {child: parent for parent in root.iter() for child in parent}
    rules = {}
    for style in [e for e in root.iter() if e.tag == SVG_NS + "style"]:
        text = re.sub(r"/\*.*?\*/", "", style.text or "", flags=re.S)
        for selector, body in re.findall(r"([^{}]+)\{([^{}]*)\}", text):
            for one_selector in selector.split(","):
                one_selector = one_selector.strip()
                if not re.fullmatch(r"\.[-\w]+", one_selector):
                    raise SystemExit(
                        "brand-paths/%s: <style> carries the selector %r, which this "
                        "generator only handles as a plain class" % (slug, one_selector)
                    )
                rules.setdefault(one_selector[1:], []).append(body.strip().strip(";"))
        parents[style].remove(style)

    for el in root.iter():
        names = (el.get("class") or "").split()
        if not names:
            continue
        del el.attrib["class"]
        # The element's own `style` wins, so it goes last.
        declarations = [d for n in names for d in rules.get(n, [])]
        if el.get("style"):
            declarations.append(el.get("style").strip().strip(";"))
        if declarations:
            el.set("style", "; ".join(declarations))
    return root


def _single_ink(path, slug):
    """The one colour a monochrome file paints with, black when it names none.

    Refuses anything with a second colour: a pair is only two INKS of one
    drawing, and a two-colour half would come out of this as a mark repainted
    in somebody else's idea of its colour.
    """
    text = io.open(path, encoding="utf-8").read()
    colours = {c.lower() for c in re.findall(r"#[0-9a-fA-F]{3,6}", text)}
    if len(colours) > 1:
        raise SystemExit("%s paints in %d colours; a pair half must be one ink" % (path.name, len(colours)))
    if not colours:
        return "#000000"  # no fill named anywhere: SVG's own default
    ink = colours.pop()
    return "#" + "".join(c * 2 for c in ink[1:]) if len(ink) == 4 else ink


def pair(name, slug, note, source, licence):
    """One drawing supplied in two inks, picked by theme rather than computed.

    `-dark` is the dark ink, for a light ground; `-light` the white one, for a
    dark ground. Where a brand has drawn both, that beats the lightness shift
    further up this file every time: the shift is this generator's guess at
    what a lighter version of a colour should be, and these are what the owner
    actually drew.
    """
    dark_file = BRAND_DIR / (slug + "-dark.svg")
    light_file = BRAND_DIR / (slug + "-light.svg")
    dark_ink = _single_ink(dark_file, slug)
    light_ink = _single_ink(light_file, slug)

    # The two files must be the same drawing. If they are not, one component
    # cannot serve both and saying so beats shipping whichever happened to be
    # parsed first.
    geometry = [re.findall(r'\sd="([^"]+)"', io.open(f, encoding="utf-8").read()) for f in (dark_file, light_file)]
    if geometry[0] != geometry[1] or not geometry[0]:
        raise SystemExit("%s: the two inks are not the same drawing" % slug)

    root = _inline_css(ET.fromstring(io.open(dark_file, encoding="utf-8").read()), slug)
    box = root.get("viewBox")
    if not box:
        raise SystemExit("brand-paths/%s-dark.svg has no viewBox" % slug)

    variable = "--brand-%s-0" % slug
    VARIABLES.append((variable, light_ink, dark_ink))

    # Every shape loses its own fill and takes the property from the root, which
    # is what makes one geometry answer to both inks.
    ids = {}
    body = "\n".join(c for c in (_jsx(k, ids, slug, 3) for k in root) if c)
    body = re.sub(r'\s+fill="[^"]*"', "", body)

    return f'''/** {note}. Source: {source} ({licence}), in both its inks */
export function {name}(props: SVGProps<SVGSVGElement>) {{
  return (
    <svg viewBox="{box}" width="1em" height="1em" fill="var({variable})" aria-hidden {{...props}}>
{body}
    </svg>
  )
}}
'''


def local(name, slug, note, source, licence):
    # A brand that supplied both of its inks is drawn from the pair instead.
    if not (BRAND_DIR / (slug + ".svg")).is_file():
        return pair(name, slug, note, source, licence)
    path = BRAND_DIR / (slug + ".svg")
    root = _inline_css(ET.fromstring(io.open(path, encoding="utf-8").read()), slug)

    # The SOURCE's box: its own if it has one, otherwise built from width and
    # height. Several of these carry only a size, and a component with no
    # viewBox does not scale to the 1em the interface asks for.
    #
    # The source's rather than a tightened one, because the plate rule below
    # measures a candidate rectangle against THIS: a plate is full-bleed by
    # definition, so it can only be recognised against the canvas it bleeds to.
    # Handing it a box already cropped to the ink made it miss Linkbox's plate
    # entirely, which then came back into the mark as a coloured square.
    box = root.get("viewBox")
    if not box:
        w, h = root.get("width"), root.get("height")
        if not w or not h:
            raise SystemExit("brand-paths/%s.svg has neither viewBox nor size" % slug)
        box = "0 0 %s %s" % (w, h)

    _drop_plate(root, path, slug)

    ids = {}
    for el in root.iter():
        if el.get("id"):
            ids[el.get("id")] = "%s-%s" % (slug, el.get("id"))

    kids = [c for c in (_jsx(k, ids, slug, 3) for k in root) if c]
    if not kids:
        raise SystemExit("brand-paths/%s.svg is empty" % slug)
    body = "\n".join(kids)

    # The ROOT's own painting attributes come along. Dropping them was a real
    # defect: Yandex's file carries its whole colour as `fill` on the `<svg>`
    # and nowhere else, so the mark came out black - and then read as a mark
    # that simply has no colour rather than as one this generator threw away.
    skip = {"viewBox", "width", "height", "id", "class", "role", "style", "x", "y"}
    root_attrs = []
    for raw, value in root.attrib.items():
        if raw.startswith("{") or raw in skip or _camel(raw) in ("xmlns", "xmlnsXlink", "version"):
            continue
        root_attrs.append('%s="%s"' % (_camel(raw), value))

    # A file that names no colour ANYWHERE paints in SVG's default, which is
    # black - and black is exactly what disappears on a dark ground. Saying so
    # explicitly is what lets the readability check below see it at all;
    # Pixeldrain's mark is one such file and was invisible because of it.
    # What the mark PAINTS with, which is not everything that names a colour.
    #
    # A `<mask>` is drawn in white to mean "show all of this" and in black to
    # mean "hide it"; neither is ink, and neither is on screen. Quatrix's file
    # carries two such masks, so the readability check saw a white it would
    # never draw, called the mark readable on a dark ground on the strength of
    # it, and left the orange that IS drawn at 1.74 against the light theme's
    # hover. Worse, had the mark been flipped, the shift would have moved the
    # mask's white along with everything else - and a mask painted in grey
    # shows the drawing at grey's opacity, which is a logo fading out rather
    # than a logo changing colour.
    painted_text = re.sub(r"<mask\b.*?</mask>", " ", body, flags=re.S) + " " + " ".join(root_attrs)
    found = re.findall(
        r'"(#[0-9a-fA-F]{3,8}|rgb\([^"]*\)|%s)"' % "|".join(KEYWORDS),
        painted_text,
    )

    # Any OTHER word where a colour belongs is refused rather than rendered.
    # A value nothing here can measure is a value the readability check silently
    # skips, and the mark then ships half-flipped - which is exactly what put.io
    # did with `fill="white"` for as long as its own plate hid the consequence.
    for attribute in ("fill", "stroke"):
        for value in re.findall(r'%s="([^"]*)"' % attribute, painted_text):
            if value in ("none", "currentColor", "transparent") or value.startswith("var(") \
                    or value.startswith("url(") or value.startswith("#") \
                    or value.startswith("rgb") or value.lower() in KEYWORDS:
                continue
            raise SystemExit(
                "%s paints with %s=\"%s\", which nothing here can measure. Add it to "
                "KEYWORDS with its hex, or give the file a real colour." % (slug, attribute, value)
            )
    if not found:
        root_attrs.append('fill="#000000"')
        found = ["#000000"]

    swap = themed(found, slug)
    body = apply_swap(body, swap)
    root_attrs = [apply_swap(a, swap) for a in root_attrs]
    painted = ("".join(" " + a for a in root_attrs))

    # Whatever the file paints WITH stays: `fill`, `style`, gradients, groups
    # and all. A mark drawn in several tones is several tones, and flattening
    # one to a single ink would be redrawing somebody's logo.
    return f'''/** {note}. Source: {source} ({licence}) */
export function {name}(props: SVGProps<SVGSVGElement>) {{
  return (
    <svg viewBox="{box}"{painted} width="1em" height="1em" aria-hidden {{...props}}>
{body}
    </svg>
  )
}}
'''


