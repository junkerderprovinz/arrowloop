# ---------------------------------------------------------------------------
# Marks that vanish into the surface they sit on.
#
# "Original und farbig" has one failure mode, and it is not a matter of taste:
# a brand whose logo is navy or black disappears on a dark ground, and one
# whose logo is near-white disappears on a light one. Measured on the running
# app, ShareFile reached a contrast of 1.07 against the dark row and OpenCloud
# 1.09 - which is to say they were there and could not be seen. Making the
# logos bigger made the invisible ones more conspicuously invisible.
#
# jdp: "lass sie flippen. auf dunklem hintergrund sollen sie hell sein, auf
# hellem hintergrund sollen sie so bleiben." So a mark that cannot be read
# against one ground gets a variant for that ground ONLY, keeping its own hue
# and saturation and moving only its lightness. It is the same logo in the same
# colour family, turned up or down until it can be seen, which is what a brand
# guideline does for its own dark backgrounds.
#
# Decided HERE, from the colours themselves, rather than in a hand-kept list of
# names: a list of "these six are too dark" is wrong the moment a mark is added
# or a set changes a hex, and nothing would say so.
SURFACE_DARK = "#393939"   # --carbon-surface2, dark theme: what a row is filled with
SURFACE_LIGHT = "#e8e8e8"  # --carbon-surface2, light theme

# A tile is not one ground, it is three, and measuring only the resting one is
# how eleven marks shipped invisible.
#
# The picker's tile is filled with --carbon-surface2 and lights up under the
# pointer, which in the dark theme means it goes to WHITE. So a mark that sits
# on #393939 at rest sits on #ffffff a moment later, and thirteen values across
# eleven marks fell under the floor against it, eight of them at exactly 1.00 -
# not faint, gone, and gone exactly while somebody was pointing at the thing
# they wanted to read. The
# light theme has the milder half of the same fault: its hover is
# --carbon-surface3 at #d1d1d1, where Cloudflare's orange falls to 1.74.
#
# Two answers, and both are needed. A mark's LIGHT value has to clear the floor
# on every light ground it can land on, which is what this tuple is for. And a
# dark-theme tile that has gone white is showing a light ground, so the mark
# switches to its light value for as long as the pointer is there - see the
# fourth CSS block at the bottom of this file.
GROUNDS_LIGHT = ("#ffffff", SURFACE_LIGHT, "#d1d1d1")

# Below this, the mark is not readable against that ground. The number is where
# the measurement and the eye agree: Dropbox's blue sits at 2.28 and reads
# perfectly well; Filen's black at 1.90 does not.
FLOOR = 2.0
# What a flipped colour has to reach. 4.5 is the text threshold rather than the
# 3.0 for graphics, because a mark this small is closer to a letterform than to
# an illustration.
TARGET = 4.5


# The colour KEYWORDS that turn up in these files, and the reason they are
# handled at all.
#
# put.io's mark writes its light half as `fill="white"`, and every measurement
# in this file looked for a hex or an `rgb(...)` - so that half was invisible to
# the readability check, which then flipped the other half and left this one
# alone. It went unnoticed for as long as the mark carried its own dark plate:
# white on its own plate reads fine, and dropping the plate is what exposed it.
#
# Two keywords rather than the full CSS table on purpose. White and black are
# exactly the two that vanish against one of the two grounds, and anything else
# is refused loudly below rather than passed through - a `fill="navy"` that
# nothing measures is the same defect wearing a different word.
KEYWORDS = {"white": "#ffffff", "black": "#000000"}


def _rgb(colour):
    """`#a00`, `#aa0000`, `rgb(170, 0, 0)` or a known keyword, as 0-255."""
    text = KEYWORDS.get(colour.strip().lower(), colour).strip()
    if text.startswith("rgb"):
        parts = re.findall(r"[\d.]+%?", text)[:3]
        if len(parts) < 3:
            return None
        # `rgb(28.2%,58%,99.6%)` is how a Cairo-exported gradient stop writes
        # itself, and reading those three as 0-255 turns a bright blue into a
        # navy - which is exactly the mistake this whole section exists to
        # catch, so getting it wrong here would flip a mark that reads fine.
        return tuple(
            int(round(float(p[:-1]) * 255 / 100)) if p.endswith("%") else int(float(p))
            for p in parts
        )
    text = text.lstrip("#")
    if len(text) == 3:
        text = "".join(c * 2 for c in text)
    if len(text) != 6:
        return None
    return tuple(int(text[i:i + 2], 16) for i in (0, 2, 4))


def _luminance(rgb):
    def channel(value):
        value /= 255.0
        return value / 12.92 if value <= 0.03928 else ((value + 0.055) / 1.055) ** 2.4
    r, g, b = (channel(v) for v in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(one_colour, other):
    a, b = sorted((_luminance(_rgb(one_colour)), _luminance(_rgb(other))), reverse=True)
    return (a + 0.05) / (b + 0.05)


def on_light_grounds(colour):
    """The WORST contrast this colour reaches on any light ground it can sit on.

    The question a mark has to answer is not "can it be read where it rests"
    but "can it be read anywhere it lands", and a tile lands it on three
    different lights: white when a dark-theme tile is hovered, #e8e8e8 at rest
    in the light theme, #d1d1d1 when that one is hovered. A near-white colour
    is worst against white, a dark one worst against #d1d1d1, so neither ground
    alone is the test and the minimum is.
    """
    return min(contrast(colour, ground) for ground in GROUNDS_LIGHT)


def shift(colour, surface, upward, also=()):
    """The same colour, moved along lightness until it can be seen.

    Hue and saturation are untouched: this is the brand's colour at a different
    brightness, not a different colour. Black and white have no hue to keep, so
    they simply become their opposite end, which is what one wants anyway.

    `also` names further (ground, minimum) pairs the result must satisfy on top
    of reaching TARGET on `surface`. It exists because the light theme has two
    grounds rather than one: a colour tuned to 4.5 against the resting
    #e8e8e8 can still sit under the floor against the #d1d1d1 it moves to
    under the pointer, and a mark that vanishes exactly while somebody points
    at it is worse than one that was always faint.
    """
    rgb = _rgb(colour)
    hue, light, sat = colorsys.rgb_to_hls(*(v / 255.0 for v in rgb))
    step = 0.02 if upward else -0.02
    limit = 0.94 if upward else 0.10
    while (light < limit) if upward else (light > limit):
        light += step
        candidate = "#%02x%02x%02x" % tuple(
            round(v * 255) for v in colorsys.hls_to_rgb(hue, min(max(light, 0.0), 1.0), sat)
        )
        if contrast(candidate, surface) >= TARGET and all(
            contrast(candidate, ground) >= minimum for ground, minimum in also
        ):
            return candidate
    return "#%02x%02x%02x" % tuple(
        round(v * 255) for v in colorsys.hls_to_rgb(hue, min(max(light, 0.0), 1.0), sat)
    )


