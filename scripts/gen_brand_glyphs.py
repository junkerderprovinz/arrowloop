# Marks drawn in their brand colours vanish on one of the grounds: navy or black
# on the dark theme, near-white on the light one. A mark that cannot be read on
# one ground gets a variant for that ground only, same hue and saturation with
# its lightness moved until it can be seen. Which marks need it is measured from
# the colours rather than kept as a list of names.
SURFACE_DARK = "#393939"   # --carbon-surface2, dark theme: what a row is filled with
SURFACE_LIGHT = "#e8e8e8"  # --carbon-surface2, light theme

# A shifted light value lands on three grounds: the white card, a tile's own
# #e8e8e8 and the light theme's row hover at #d1d1d1.
GROUNDS_LIGHT = ("#ffffff", SURFACE_LIGHT, "#d1d1d1")

# Below this contrast a mark is not readable against a ground: Dropbox's blue at
# 2.28 reads well, Filen's black at 1.90 does not.
FLOOR = 2.0
# The light theme keeps a brand's own colour down to this ("Brand tiles" in
# GlimStone): an orange still reads as orange on light grey, because the hue does
# the recognising, and only white and near-white parts vanish.
LIGHT_FLOOR = 1.35
# What a flipped colour has to reach: the text threshold rather than the 3.0 for
# graphics, since a mark this small is closer to a letterform.
TARGET = 4.5


# Colour keywords found in these files (put.io writes `fill="white"`). Any other
# keyword is refused below, since the readability check could not measure it.
KEYWORDS = {"white": "#ffffff", "black": "#000000"}


def _rgb(colour):
    """`#a00`, `#aa0000`, `rgb(170, 0, 0)` or a known keyword, as 0-255."""
    text = KEYWORDS.get(colour.strip().lower(), colour).strip()
    if text.startswith("rgb"):
        parts = re.findall(r"[\d.]+%?", text)[:3]
        if len(parts) < 3:
            return None
        # Cairo exports write `rgb(28.2%,58%,99.6%)`; read as 0-255 that bright
        # blue would become navy.
        return tuple(
            int(round(float(p[:-1]) * 255 / 100)) if p.endswith("%") else int(float(p))
            for p in parts
        )
    text = text.lstrip("#")
    if len(text) == 3:
        text = "".join(c * 2 for c in text)
    if len(text) != 6:
        return None
    return tuple(int(text[i:i + 2], 16) for i in (0, 2, 4))


def _luminance(rgb):
    def channel(value):
        value /= 255.0
        return value / 12.92 if value <= 0.03928 else ((value + 0.055) / 1.055) ** 2.4
    r, g, b = (channel(v) for v in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(one_colour, other):
    a, b = sorted((_luminance(_rgb(one_colour)), _luminance(_rgb(other))), reverse=True)
    return (a + 0.05) / (b + 0.05)


def on_light_grounds(colour):
    """The worst contrast this colour reaches on any light ground it can land
    on. A near-white colour is worst against white, a dark one against
    #d1d1d1."""
    return min(contrast(colour, ground) for ground in GROUNDS_LIGHT)


def shift(colour, surface, upward, also=()):
    """The same colour, moved along lightness until it can be seen.

    Hue and saturation are untouched; black and white have no hue and become
    their opposite end. `also` names further (ground, minimum) pairs the result
    must satisfy on top of reaching TARGET on `surface`, since a colour tuned
    against the resting #e8e8e8 can still fall under the floor on the hovered
    #d1d1d1.
    """
    rgb = _rgb(colour)
    hue, light, sat = colorsys.rgb_to_hls(*(v / 255.0 for v in rgb))
    step = 0.02 if upward else -0.02
    limit = 0.94 if upward else 0.10
    while (light < limit) if upward else (light > limit):
        light += step
        candidate = "#%02x%02x%02x" % tuple(
            round(v * 255) for v in colorsys.hls_to_rgb(hue, min(max(light, 0.0), 1.0), sat)
        )
        if contrast(candidate, surface) >= TARGET and all(
            contrast(candidate, ground) >= minimum for ground, minimum in also
        ):
            return candidate
    return "#%02x%02x%02x" % tuple(
        round(v * 255) for v in colorsys.hls_to_rgb(hue, min(max(light, 0.0), 1.0), sat)
    )


