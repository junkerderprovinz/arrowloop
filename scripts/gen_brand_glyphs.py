    ("IconBox", "box", "Box"),
    ("IconProtonDrive", "protondrive", "Proton Drive"),
    ("IconICloud", "icloud", "iCloud Drive"),
    ("IconMailru", "maildotru", "Mail.ru Cloud"),
    ("IconYandex", "yandexcloud", "Yandex Disk"),
