def _drop_plate(root, source, slug):
    """Remove the rectangle the rest of the mark is sitting ON.

    A brand's own asset is often drawn on its plate: a rectangle in the brand's
    dark, with the mark in white on top. That is right for a press kit and
    wrong in a list of fifty logos, where every OTHER mark sits on the page and
    this one arrives in its own box. jdp reported it twice, about two different
    files - "opendrive logo ohne den dunklen hintergrund" and, of Uloz.to, "hat
    noch ein hintergrund".

    Measured rather than listed by name, because a list of names only ever
    contains the files somebody has already complained about.

    A plate is defined here by CONTAINMENT: the first thing drawn is a
    rectangle, and everything else drawn fits inside it. That is what a plate
    is, and it is a better definition than the one this had first, which asked
    whether the rectangle filled the CANVAS. Linkbox is why: its file is a
    367x70 wordmark canvas whose text was lost on export, so the plate covers
    the symbol block and about a fifth of the canvas - not full-bleed by any
    measure, and a plate to anybody looking at it.

    What it does NOT do is guess about colour. Dropping the plate can leave a
    white mark invisible on a light page, and the answer to that is FORCE_THEMED
    above, which says so per file and in as many words.
    """
    if svgelements is None:
        raise SystemExit("the plate rule needs svgelements (pip install svgelements)")
    try:
        drawing = svgelements.SVG.parse(str(source))
    except Exception:
        return

    boxes = []
    for element in drawing.elements():
        if not isinstance(element, svgelements.Shape):
            continue
        try:
            bounds = element.bbox()
        except Exception:
            continue
        if bounds:
            boxes.append((type(element).__name__, bounds))
    if len(boxes) < 2 or boxes[0][0] != "Rect":
        return

    plate = boxes[0][1]
    rest = boxes[1:]
    # Half a unit of tolerance: these come out of drawing programs, and a plate
    # a rounding short of covering the mark is still the mark's plate.
    covers = (
        plate[0] <= min(b[0] for _, b in rest) + 0.5
        and plate[1] <= min(b[1] for _, b in rest) + 0.5
        and plate[2] >= max(b[2] for _, b in rest) - 0.5
        and plate[3] >= max(b[3] for _, b in rest) - 0.5
    )
    if not covers:
        return

    parents = {child: parent for parent in root.iter() for child in parent}
    for el in root.iter():
        if el.tag == SVG_NS + "rect":
            parents[el].remove(el)
            print("  %s: dropped the plate it was sitting on (%gx%g)"
                  % (slug, plate[2] - plate[0], plate[3] - plate[1]))
            return


def themed(colours, slug):
    """Which of these colours need a per-theme variant, and under what names.

    Returns a map from the colour AS WRITTEN in the file to the `var(...)` that
    replaces it, empty when the mark reads fine on both grounds.

    Judged per MARK rather than per colour: a two-tone logo with one readable
    half would come out half flipped and half not, which is no longer the logo.
    """
    usable = [c for c in colours if _rgb(c)]
    if not usable:
        return {}

    # The named exceptions first: a colour listed here follows the theme
    # whatever the measurement says about the mark as a whole.
    forced = {}
    for colour, (on_dark, on_light) in FORCE_THEMED.get(slug, {}).items():
        if colour not in usable:
            raise SystemExit("FORCE_THEMED names %s in %s, which does not paint with it" % (colour, slug))
        # A hand-given pair skips the measurement that mints every other value,
        # so it gets the measurement here instead. Without this, the one place
        # in the file where a human picks the hex is the one place a hex can be
        # too faint to see and nothing says so.
        if contrast(on_dark, SURFACE_DARK) < FLOOR or on_light_grounds(on_light) < FLOOR:
            raise SystemExit(
                "FORCE_THEMED %s/%s is too faint: %.2f on the dark ground, %.2f on the "
                "worst light one" % (slug, colour, contrast(on_dark, SURFACE_DARK),
                                     on_light_grounds(on_light))
            )
        name = "--brand-%s-forced%d" % (slug, len(forced))
        VARIABLES.append((name, _hex(on_dark), _hex(on_light)))
        forced[colour] = "var(%s)" % name

    # Naming one colour by hand settles THAT colour, not the mark. Returning
    # here was a real hole: OpenDrive's white bars are forced, its blue ones
    # are not, and the blue was never measured at all - it sat at 1.74 against
    # the light theme's hover for as long as the exception existed. So the rest
    # of the mark goes through the same measurement as any other.
    rest = [c for c in usable if c not in forced]
    if not rest:
        return forced

    dark_best = max(contrast(c, SURFACE_DARK) for c in rest)
    light_best = max(on_light_grounds(c) for c in rest)
    if dark_best >= FLOOR and light_best >= FLOOR:
        return forced
    if dark_best < FLOOR and light_best < FLOOR:
        raise SystemExit(
            "%s cannot be read on either ground (%.2f dark, %.2f light): it needs a "
            "different source file, not a lightness shift" % (slug, dark_best, light_best)
        )
    swap = dict(forced)
    minted = {}
    for colour in rest:
        # Keyed by what the colour IS, not by how it was spelt: one file writes
        # the same navy as `#20434F` and `#20434f`, and two properties for one
        # colour is two things to keep in step for no reason.
        key = _rgb(colour)
        if key not in minted:
            name = "--brand-%s-%d" % (slug, len(minted))
            on_dark = shift(colour, SURFACE_DARK, upward=True) if dark_best < FLOOR else colour
            on_light = (
                shift(colour, SURFACE_LIGHT, upward=False,
                      also=[(ground, FLOOR) for ground in GROUNDS_LIGHT])
                if light_best < FLOOR
                else colour
            )
            VARIABLES.append((name, _hex(on_dark), _hex(on_light)))
            minted[key] = name
        swap[colour] = "var(%s)" % minted[key]
    return swap


def _hex(colour):
    """A colour as a hex string, whatever it was written as on the way in.

    Only the OUTPUT is normalised. A keyword is a perfectly good thing to find
    in somebody else's file, and a perfectly bad thing to emit: the CSS these
    variables land in is read back by the contrast guard on the other side of
    the repo, which parses hex and returns nothing for a word. That guard fell
    over on `--brand-putio-0: white` the moment the keyword became reachable -
    a blind spot answering a blind spot.
    """
    text = KEYWORDS.get(str(colour).strip().lower())
    return text or colour


def apply_swap(source, swap):
    """Put the custom properties where the literal colours were.

    Everywhere the mark PAINTS, and nowhere else. A `<mask>` block is left
    alone for the same reason its colours were never measured: white there
    means "show all of this" rather than "draw in white", and a theme variable
    in its place would make the mark's own visibility follow the theme - a
    logo that fades instead of a logo that flips.
    """
    masks = []

    def park(match):
        masks.append(match.group(0))
        return "\0mask%d\0" % (len(masks) - 1)

    source = re.sub(r"<mask\b.*?</mask>", park, source, flags=re.S)
    for colour, variable in swap.items():
        source = source.replace('"%s"' % colour, '"%s"' % variable)
    for index, block in enumerate(masks):
        source = source.replace("\0mask%d\0" % index, block)
    return source


