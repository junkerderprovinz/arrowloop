HEAD = '''import type { SVGProps } from 'react'

// ---------------------------------------------------------------------------
// Brand marks. GENERATED by scripts/gen_brand_glyphs.py - do not hand-edit.
//
// Kept apart from `glyphs.tsx` on purpose. That file is one Streamline set,
// drawn on one grid to one convention, which is what makes those icons agree
// with each other. A brand mark cannot come from there: it is somebody else's
// drawing, it must not be redrawn to fit, and it must not be swapped for a
// near neighbour when the set lacks it - a mark naming the WRONG service is
// worse than no mark, which is why several providers here deliberately have
// none.
//
// Source: Simple Icons (simpleicons.org), published under CC0. No attribution
// is required; it is given because knowing where a drawing came from is worth
// more than the licence demands.
//
// TRADEMARKS. Every mark below belongs to its owner. Each is used the one way a
// trademark may be used without permission: to name the thing it refers to. A
// mark appears only on a row that connects to exactly that service, each is
// reproduced unmodified apart from taking `currentColor`, and nothing here
// claims endorsement by or affiliation with any of them.
//
// The design language's other half of this rule: a brand mark is never
// reachable by PATTERN from a translation key. It is passed at the call site
// that means it.
// ---------------------------------------------------------------------------

'''


def one(name: str, slug: str, note: str) -> str:
    svg = io.open(SRC / (slug + ".svg"), encoding="utf-8").read()
    box = re.search(r'viewBox="([^"]+)"', svg)
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if not box or not paths:
        raise SystemExit("cannot read %s.svg" % slug)
    body = "\n".join('      <path d="%s" />' % d for d in paths)
    return f'''/** {note}. Simple Icons: {slug} */
export function {name}(props: SVGProps<SVGSVGElement>) {{
  return (
    <svg viewBox="{box.group(1)}" width="1em" height="1em" fill="currentColor" aria-hidden {{...props}}>
{body}
    </svg>
  )
}}
'''


if not SRC.is_dir():
    raise SystemExit("no such directory: %s\nInstall simple-icons and pass its icons path." % SRC)

parts = [HEAD] + [one(*m) for m in MARKS]
io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(parts))
print("%s: %d marks" % (OUT.name, len(MARKS)))
