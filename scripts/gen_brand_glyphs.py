# So a mark written back out for measuring keeps its plain tag names.
ET.register_namespace("", "http://www.w3.org/2000/svg")
ET.register_namespace("xlink", "http://www.w3.org/1999/xlink")

# Hand-set viewBoxes for a mark crop_to_ink measures wrongly, by component name.
# An entry that only restates the measurement is refused.
INK = {}

# How much of its box a mark may waste before it is cropped: above the rounding
# in these files and below what the eye resolves.
SLACK = 1.02

# Redundant INK entries, refused together at the end of the run.
REDUNDANT = []


def _measure_ink(component, name):
    """The box the mark actually paints in, in its own viewBox units.

    Measured off the finished markup, after the plate is dropped, the styles
    folded in and the ids prefixed. `<defs>`, `<mask>` and `<clipPath>` are cut
    out first, since a full-canvas mask rectangle (Quatrix has two) would report
    the whole box as painted.
    """
    if svgelements is None:
        raise SystemExit(
            "crop_to_ink needs the svgelements package (pip install svgelements).\n"
            "It measures where each mark actually paints."
        )
    markup = component[component.index("<svg"):component.rindex("</svg>") + 6]
    markup = markup.replace(" aria-hidden {...props}", " ").replace("{...props}", " ")

    # JSX spellings back to SVG's own, for the attributes these files carry.
    def style(match):
        pairs = re.findall(r'(\w+):\s*"([^"]*)"', match.group(1))
        return 'style="%s"' % ";".join(
            "%s:%s" % (re.sub(r"(?<!^)(?=[A-Z])", "-", key).lower(), value)
            for key, value in pairs
        )

    markup = re.sub(r"style=\{\{([^}]*)\}\}", style, markup)
    for jsx, svg in (
        ("fillRule", "fill-rule"), ("fillOpacity", "fill-opacity"),
        ("clipPath", "clip-path"), ("clipRule", "clip-rule"),
        ("strokeWidth", "stroke-width"), ("strokeLinecap", "stroke-linecap"),
        ("strokeLinejoin", "stroke-linejoin"), ("strokeMiterlimit", "stroke-miterlimit"),
        ("stopColor", "stop-color"), ("stopOpacity", "stop-opacity"),
        ("xlinkHref", "xlink:href"), ("fillOpacity", "fill-opacity"),
    ):
        markup = markup.replace(jsx + "=", svg + "=")
    for tag in ("defs", "mask", "clipPath"):
        markup = re.sub(r"<%s\b.*?</%s>" % (tag, tag), "", markup, flags=re.S)

    box = [float(v) for v in re.search(r'viewBox="([^"]+)"', markup).group(1).replace(",", " ").split()]
    # The parser cannot resolve `width="1em"`. The viewBox's own size makes the
    # viewport transform the identity, so the results are in viewBox units.
    markup = re.sub(r'\swidth="[^"]*"', "", markup, count=1)
    markup = re.sub(r'\sheight="[^"]*"', "", markup, count=1)
    markup = markup.replace(
        "<svg ",
        '<svg xmlns="http://www.w3.org/2000/svg" width="%g" height="%g" ' % (box[2], box[3]),
        1,
    )

    handle, path = tempfile.mkstemp(suffix=".svg")
    os.close(handle)
    try:
        io.open(path, "w", encoding="utf-8").write(markup)
        drawing = svgelements.SVG.parse(path)
    finally:
        os.unlink(path)

    left = top = float("inf")
    right = bottom = float("-inf")
    for element in drawing.elements():
        if not isinstance(element, svgelements.Shape):
            continue
        try:
            # With the stroke, since a mark drawn as an outline (Oracle Cloud's
            # 4-unit stroke) would otherwise lose half of it at every edge.
            bounds = element.bbox(with_stroke=True)
        except Exception:
            continue
        if not bounds:
            continue
        left, top = min(left, bounds[0]), min(top, bounds[1])
        right, bottom = max(right, bounds[2]), max(bottom, bounds[3])
    if right <= left or bottom <= top:
        raise SystemExit("%s paints nothing this can measure" % name)
    # Back into the box's own coordinates: the parse put its origin at 0,0.
    return box, (left + box[0], top + box[1], right - left, bottom - top)


# What a lit tile does with a mark ("Brand tiles" in GlimStone): every part
# turns the tile's ink, except a part lying on a part of another colour, which
# becomes a cut-out in the tile colour, like the M on MEGA's disc or the eyes on
# PikPak's face. A part at most this far from the colour under it is the same
# surface drawn twice, not a detail on it (Euclidean distance in 0-255 RGB).
SAME_SURFACE = 60
# How much of a part's box has to lie on another part for it to count as lying
# on it. Boxes, not shapes, so the margin covers a round part on a square box.
ON_TOP = 0.8
# Elements that paint nothing of their own.
NOT_PAINT = ("defs", "mask", "clipPath", "pattern", "symbol", "linearGradient", "radialGradient", "marker")
SHAPES = ("path", "circle", "rect", "ellipse", "polygon", "polyline", "line", "use")


def _local_name(el):
    return el.tag.split("}")[-1]


def _declared(el, prop):
    """A paint property as the element itself declares it, style over attribute."""
    style = el.get("style") or ""
    found = re.search(r"(?:^|;)\s*%s\s*:\s*([^;]+)" % prop, style)
    return found.group(1).strip() if found else el.get(prop)


def _gradient_colour(root, ref):
    """The colour in the middle of a gradient, following `href` to the gradient
    whose stops it borrows."""
    by_id = {el.get("id"): el for el in root.iter() if el.get("id")}
    grad = by_id.get(ref)
    while grad is not None:
        stops = [s for s in grad if _local_name(s) == "stop"]
        if stops:
            def offset(stop):
                text = stop.get("offset", "0").strip()
                return float(text[:-1]) / 100 if text.endswith("%") else float(text)
            mid = min(stops, key=lambda s: abs(offset(s) - 0.5))
            return _declared(mid, "stop-color")
        href = grad.get("href") or grad.get("{http://www.w3.org/1999/xlink}href")
        grad = by_id.get(href[1:]) if href else None
    return None


def roles(root, slug):
    """Mark every painted part of a mark as ink or cut-out for a lit tile.

    Each part's fill (and stroke) is rewritten to `var(--mark-ink, <own>)` or
    `var(--mark-cut, <own>)`, keeping its own colour at rest. Returns the colours
    that paint straight onto the page, which the light theme may have to deepen,
    and the tile colour: the colour covering most of the mark, cut-outs and
    near-white left out, the middle of a gradient for a gradient.
    """
    if svgelements is None:
        raise SystemExit("roles needs the svgelements package (pip install svgelements)")
    parents = {child: parent for parent in root.iter() for child in parent}

    def hidden(el):
        while el in parents:
            el = parents[el]
            if _local_name(el) in NOT_PAINT:
                return True
        return False

    def inherited(el, prop):
        while el is not None:
            value = _declared(el, prop)
            if value:
                return value
            el = parents.get(el)
        return "#000000" if prop == "fill" else None

    def colour_of(value):
        if not value or value in ("none", "transparent"):
            return None
        ref = re.match(r"url\(#([^)]+)\)", value)
        if ref:
            value = _gradient_colour(root, ref.group(1))
            return _rgb(value) if value else None
        return _rgb(value)

    parts = []
    for index, el in enumerate(el for el in root.iter() if _local_name(el) in SHAPES and not hidden(el)):
        el.set("data-part", str(index))
        fill, stroke = inherited(el, "fill"), inherited(el, "stroke")
        paint = colour_of(fill) or colour_of(stroke)
        if paint:
            parts.append({"el": el, "fill": fill, "stroke": stroke, "rgb": paint})

    handle, path = tempfile.mkstemp(suffix=".svg")
    os.close(handle)
    try:
        io.open(path, "w", encoding="utf-8").write(ET.tostring(root, encoding="unicode"))
        drawing = svgelements.SVG.parse(path)
    finally:
        os.unlink(path)
    boxes = {}
    for element in drawing.elements():
        key = element.values.get("data-part") if hasattr(element, "values") else None
        if key is None or not isinstance(element, svgelements.Shape):
            continue
        try:
            bounds = element.bbox(with_stroke=True)
        except Exception:
            bounds = None
        if bounds:
            boxes[key] = bounds
    for part in parts:
        part["box"] = boxes.get(part["el"].get("data-part"))
    parts =[p for p in parts if p["box"] and (p["box"][2] - p["box"][0]) * (p["box"][3] - p["box"][1]) > 0]
    for el in root.iter():
        el.attrib.pop("data-part", None)

    def area(box):
        return (box[2] - box[0]) * (box[3] - box[1])

    def lies_on(a, b):
        w = min(a[2], b[2]) - max(a[0], b[0])
        h = min(a[3], b[3]) - max(a[1], b[1])
        return w > 0 and h > 0 and w * h / area(a) >= ON_TOP

    def apart(a, b):
        return sum((x - y) ** 2 for x, y in zip(a, b)) ** 0.5 > SAME_SURFACE

    for i, part in enumerate(parts):
        part["depth"] = 0
        for below in reversed(parts[:i]):
            if lies_on(part["box"], below["box"]):
                part["depth"] = below["depth"] + (1 if apart(part["rgb"], below["rgb"]) else 0)
                break
    # A part under a larger one of another colour shows only through that
    # one's holes, as MEGA's white disc shows through the M.
    for i, part in enumerate(parts):
        for above in parts[i + 1:]:
            if lies_on(part["box"], above["box"]) and apart(part["rgb"], above["rgb"]):
                if above["depth"] % 2 == part["depth"] % 2:
                    part["depth"] = above["depth"] + 1
                break

    for part in parts:
        role = "--mark-cut" if part["depth"] % 2 else "--mark-ink"
        el = part["el"]
        for prop in ("fill", "stroke"):
            value = part[prop]
            if not value or value in ("none", "transparent"):
                continue
            wrapped = "var(%s, %s)" % (role, value)
            style = el.get("style") or ""
            if re.search(r"(?:^|;)\s*%s\s*:" % prop, style):
                el.set("style", re.sub(r"((?:^|;)\s*%s\s*:\s*)[^;]+" % prop, lambda m: m.group(1) + wrapped, style))
            else:
                el.set(prop, wrapped)

    ground = {p["rgb"] for p in parts if p["depth"] == 0}
    cover = {}
    for p in parts:
        if p["depth"] % 2 == 0 and min(p["rgb"]) <= 216:
            cover[p["rgb"]] = cover.get(p["rgb"], 0) + area(p["box"])
    # A white shape carrying its detail in colour, like Filen's disc and strokes.
    if not cover:
        for p in parts:
            if min(p["rgb"]) <= 216:
                cover[p["rgb"]] = cover.get(p["rgb"], 0) + area(p["box"])
    tile = "#%02x%02x%02x" % max(cover, key=cover.get) if cover else None
    return ground, tile


def crop_to_ink(component, name):
    """Tighten a mark's viewBox onto its drawing, since a tile scales the box
    and a drawing in a box twice its height arrives at half the size of its
    neighbours."""
    declared, ink = _measure_ink(component, name)
    slack_x = declared[2] / ink[2]
    slack_y = declared[3] / ink[3]
    # `or 0.0` turns a measured -0.0 into 0, so rounding never writes "-0".
    tight = "%s %s %s %s" % tuple(
        (("%.2f" % (round(value, 2) or 0.0)).rstrip("0").rstrip(".") or "0") for value in ink
    )

    if name in INK:
        if slack_x <= SLACK and slack_y <= SLACK:
            REDUNDANT.append((name, INK[name], tight))
        else:
            print("  %s: kept its override %s over the measured %s"
                  % (name, INK[name], tight))
        return component

    if slack_x <= SLACK and slack_y <= SLACK:
        return component
    print("  %s: cropped to its ink (%.2fx wide, %.2fx tall)" % (name, slack_x, slack_y))
    cropped, hits = re.subn(r'viewBox="[^"]*"', 'viewBox="%s"' % tight, component, count=1)
    # The crop has already been announced, so a replacement that misses stops
    # the run.
    if hits != 1:
        raise SystemExit("%s: could not find its viewBox to crop" % name)
    return cropped


def _inline_css(root, slug):
    """Fold an Illustrator `<style>` block into the elements it paints.

    Class names are global to the document, so two marks both defining `.st0`
    would share one fill. This runs before the JSX pass, so a `url(#…)` inside
    a rule gets the same id prefix as every other reference.
    """
    parents = {child: parent for parent in root.iter() for child in parent}
    rules = {}
    for style in [e for e in root.iter() if e.tag == SVG_NS + "style"]:
        text = re.sub(r"/\*.*?\*/", "", style.text or "", flags=re.S)
        for selector, body in re.findall(r"([^{}]+)\{([^{}]*)\}", text):
            for one_selector in selector.split(","):
                one_selector = one_selector.strip()
                if not re.fullmatch(r"\.[-\w]+", one_selector):
                    raise SystemExit(
                        "brand-paths/%s: <style> carries the selector %r, which this "
                        "generator only handles as a plain class" % (slug, one_selector)
                    )
                rules.setdefault(one_selector[1:], []).append(body.strip().strip(";"))
        parents[style].remove(style)

    for el in root.iter():
        names = (el.get("class") or "").split()
        if not names:
            continue
        del el.attrib["class"]
        # The element's own `style` wins, so it goes last.
        declarations = [d for n in names for d in rules.get(n, [])]
        if el.get("style"):
            declarations.append(el.get("style").strip().strip(";"))
        if declarations:
            el.set("style", "; ".join(declarations))
    return root


def _single_ink(path, slug):
    """The one colour a monochrome file paints with, black when it names none.
    A pair half with a second colour is refused."""
    text = io.open(path, encoding="utf-8").read()
    colours = {c.lower() for c in re.findall(r"#[0-9a-fA-F]{3,6}", text)}
    if len(colours) > 1:
        raise SystemExit("%s paints in %d colours; a pair half must be one ink" % (path.name, len(colours)))
    if not colours:
        return "#000000"  # no fill named anywhere: SVG's own default
    ink = colours.pop()
    return "#" + "".join(c * 2 for c in ink[1:]) if len(ink) == 4 else ink


def pair(name, slug, note, source, licence):
    """One drawing supplied in two inks, picked by theme rather than computed.
    `-dark` is the dark ink, for a light ground; `-light` the white one, for a
    dark ground."""
    dark_file = BRAND_DIR / (slug + "-dark.svg")
    light_file = BRAND_DIR / (slug + "-light.svg")
    dark_ink = _single_ink(dark_file, slug)
    light_ink = _single_ink(light_file, slug)

    geometry = [re.findall(r'\sd="([^"]+)"', io.open(f, encoding="utf-8").read()) for f in (dark_file, light_file)]
    if geometry[0] != geometry[1] or not geometry[0]:
        raise SystemExit("%s: the two inks are not the same drawing" % slug)

    root = _inline_css(ET.fromstring(io.open(dark_file, encoding="utf-8").read()), slug)
    box = root.get("viewBox")
    if not box:
        raise SystemExit("brand-paths/%s-dark.svg has no viewBox" % slug)

    variable = "--brand-%s-0" % slug
    VARIABLES.append((variable, light_ink, dark_ink))
    # The ink drawn for a light ground is the brand's own.
    tile(name, slug, dark_ink)

    # Every shape takes its fill from the root, so one geometry serves both inks.
    ids = {}
    body = "\n".join(c for c in (_jsx(k, ids, slug, 3) for k in root) if c)
    body = re.sub(r'\s+fill="[^"]*"', "", body)

    return f'''/** {note}. Source: {source} ({licence}), in both its inks */
export function {name}(props: SVGProps<SVGSVGElement>) {{
  return (
    <svg viewBox="{box}" width="1em" height="1em" fill="var(--mark-ink, var({variable}))" aria-hidden {{...props}}>
{body}
    </svg>
  )
}}
'''


def local(name, slug, note, source, licence):
    if not (BRAND_DIR / (slug + ".svg")).is_file():
        return pair(name, slug, note, source, licence)
    path = BRAND_DIR / (slug + ".svg")
    root = _inline_css(ET.fromstring(io.open(path, encoding="utf-8").read()), slug)

    # The source's box, or one built from width and height, since a component
    # without a viewBox does not scale to 1em.
    box = root.get("viewBox")
    if not box:
        w, h = root.get("width"), root.get("height")
        if not w or not h:
            raise SystemExit("brand-paths/%s.svg has neither viewBox nor size" % slug)
        box = "0 0 %s %s" % (w, h)

    plate = _drop_plate(root, path, slug)
    ground, largest = roles(root, slug)
    tile(name, slug, largest or plate)

    ids = {}
    for el in root.iter():
        if el.get("id"):
            ids[el.get("id")] = "%s-%s" % (slug, el.get("id"))

    kids = [c for c in (_jsx(k, ids, slug, 3) for k in root) if c]
    if not kids:
        raise SystemExit("brand-paths/%s.svg is empty" % slug)
    body = "\n".join(kids)

    # The root's painting attributes come along: Yandex's whole colour is a
    # `fill` on the `<svg>`.
    skip = {"viewBox", "width", "height", "id", "class", "role", "style", "x", "y"}
    root_attrs = []
    for raw, value in root.attrib.items():
        if raw.startswith("{") or raw in skip or _camel(raw) in ("xmlns", "xmlnsXlink", "version"):
            continue
        root_attrs.append('%s="%s"' % (_camel(raw), value))

    # What the mark paints with. A `<mask>`'s white and black are not ink and
    # would mislead the readability check.
    painted_text = re.sub(r"<mask\b.*?</mask>", " ", body, flags=re.S) + " " + " ".join(root_attrs)
    found = re.findall(
        r'"(#[0-9a-fA-F]{3,8}|rgb\([^"]*\)|%s)"' % "|".join(KEYWORDS),
        painted_text,
    ) + re.findall(
        r'--mark-(?:ink|cut), (#[0-9a-fA-F]{3,8}|rgb\([^)]*\)|%s)\)' % "|".join(KEYWORDS),
        painted_text,
    )

    # Any other word where a colour belongs would be skipped by the readability
    # check, so it is refused.
    for attribute in ("fill", "stroke"):
        for value in re.findall(r'%s="([^"]*)"' % attribute, painted_text):
            if value in ("none", "currentColor", "transparent") or value.startswith("var(") \
                    or value.startswith("url(") or value.startswith("#") \
                    or value.startswith("rgb") or value.lower() in KEYWORDS:
                continue
            raise SystemExit(
                "%s paints with %s=\"%s\", which nothing here can measure. Add it to "
                "KEYWORDS with its hex, or give the file a real colour." % (slug, attribute, value)
            )
    # A file naming no colour paints in SVG's default black, which the
    # readability check has to see.
    if not found:
        root_attrs.append('fill="#000000"')
        found = ["#000000"]

    swap = themed(found, slug, ground)
    body = apply_swap(body, swap)
    root_attrs = [apply_swap(a, swap) for a in root_attrs]
    painted = ("".join(" " + a for a in root_attrs))

    # Fills, styles, gradients and groups stay as drawn.
    return f'''/** {note}. Source: {source} ({licence}) */
export function {name}(props: SVGProps<SVGSVGElement>) {{
  return (
    <svg viewBox="{box}"{painted} width="1em" height="1em" aria-hidden {{...props}}>
{body}
    </svg>
  )
}}
'''


