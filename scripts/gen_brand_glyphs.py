def css_block(selectors, index, indent=0):
    """One rule: its selectors, one custom property per mark, closing brace."""
    pad = " " * indent
    lines = ["%s%s," % (pad, s) for s in selectors[:-1]]
    lines.append("%s%s {" % (pad, selectors[-1]))
