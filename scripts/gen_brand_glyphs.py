# Our component name -> the Simple Icons slug, with what it is for.
#
# Several are a judgement call and are marked as such: a mark that names the
# right COMPANY but not the exact product is better than no mark, and a mark
# that names a DIFFERENT product is not. Where the second was the only option,
# the entry is left out and the provider shows a generic glyph instead.
