// translator returns the texts of the language a tag such as "de" or "pt-BR"
// names, falling back to English for a language the interface does not
// offer and for a key a table lacks.
func translator(lang string) func(key, job string, count int) string {
	base := strings.ToLower(lang)
	if i := strings.IndexAny(base, "-_"); i >= 0 {
		base = base[:i]
	}
	if base == "nb" || base == "nn" {
		base = "no"
	}
	table := texts[base]
	return func(key, job string, count int) string {
		text, ok := table[key]
		if !ok {
			text = texts["en"][key]
		}
		return strings.NewReplacer("{job}", job, "{count}", strconv.Itoa(count)).Replace(text)
	}
}

