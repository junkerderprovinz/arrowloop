type importPlan struct {
	Source  string           `json:"source"`
	Jobs    []map[string]any `json:"jobs"`
	Targets []struct {
		Name     string            `json:"name"`
		Type     string            `json:"type"`
		Settings map[string]string `json:"settings"`
	} `json:"targets"`
	FillIn  []struct{ Subject, What string } `json:"fillIn"`
	Skipped []struct{ Subject, What string } `json:"skipped"`
}

func fileBody(t *testing.T, file string) string {
	t.Helper()
	out, err := json.Marshal(map[string]string{"file": file})
	if err != nil {
		t.Fatal(err)
	}
	return string(out)
}

func importing(t *testing.T, h *harness, path, file string) (int, importPlan, string) {
	t.Helper()
	resp := h.post(t, path, fileBody(t, file))
	defer resp.Body.Close()
	raw, _ := io.ReadAll(resp.Body)
	var p importPlan
	if resp.StatusCode == http.StatusOK {
		if err := json.Unmarshal(raw, &p); err != nil {
			t.Fatalf("decode %s: %v", raw, err)
		}
	}
	return resp.StatusCode, p, string(raw)
}

func TestCheckingAnImportSavesNothing(t *testing.T) {
	h := newHarness(t)
	withRcloneConfig(t)
	before, _ := os.ReadFile(h.configPath)

	code, p, said := importing(t, h, "/api/import/check", profile)
	if code != http.StatusOK {
		t.Fatalf("check answered %d: %s", code, said)
	}
	if p.Source != "luckyBackup" {
		t.Errorf("read as %q", p.Source)
	}
	if len(p.Jobs) != 2 || p.Jobs[0]["name"] != "photos 2" || p.Jobs[1]["name"] != "Music" {
		t.Errorf("the plan names the jobs %v", p.Jobs)
	}
	if len(p.Targets) != 1 || p.Targets[0].Name != "nas.example.lan" {
		t.Errorf("the plan has targets %+v", p.Targets)
	}
	if strings.Contains(said, "not-a-real-password") {
		t.Error("the password from the profile came back")
	}

	after, _ := os.ReadFile(h.configPath)
	if string(after) != string(before) {
		t.Error("checking an import changed the configuration")
	}
	if len(remotes.List()) != 0 {
		t.Errorf("checking an import made targets: %+v", remotes.List())
	}
}

func TestAnImportAddsPausedJobsAndTargets(t *testing.T) {
	h := newHarness(t)
	withRcloneConfig(t)

	code, _, said := importing(t, h, "/api/import", profile)
	if code != http.StatusOK {
		t.Fatalf("import answered %d: %s", code, said)
	}

	var cfg struct{ Jobs []map[string]any }
	h.get(t, "/api/config", &cfg)
	if len(cfg.Jobs) != 3 {
		t.Fatalf("want the old job and two new ones, got %v", cfg.Jobs)
	}
	found := map[string]map[string]any{}
	for _, j := range cfg.Jobs {
		found[j["name"].(string)] = j
	}
	if found["photos"] == nil || found["photos 2"] == nil || found["Music"] == nil {
		t.Fatalf("the jobs are %v", cfg.Jobs)
	}
	if found["photos"]["disabled"] == true {
		t.Error("the job that was there got paused")
	}
	music := found["Music"]
	if music["disabled"] != true || music["right"] != "nas.example.lan:/srv/music" || music["state"] != "state/Music.db" {
		t.Errorf("the imported job reads %v", music)
	}
	if _, set := music["after"]; set {
		t.Error("an imported job carries a command")
	}

	list := remotes.List()
	if len(list) != 1 || list[0].Name != "nas.example.lan" || list[0].Type != "sftp" {
		t.Fatalf("the targets are %+v", list)
	}
	for _, s := range list[0].Settings {
		if s.Key == "pass" {
			t.Error("the target got a password")
		}
	}
}

func TestAFileNobodyKnowsIsRefused(t *testing.T) {
	h := newHarness(t)
	before, _ := os.ReadFile(h.configPath)
	for _, path := range []string{"/api/import/check", "/api/import"} {
		code, _, said := importing(t, h, path, "just some notes")
		if code != http.StatusBadRequest || !strings.Contains(said, `"code":"import-unknown"`) {
			t.Errorf("%s answered %d %s", path, code, said)
		}
	}
	after, _ := os.ReadFile(h.configPath)
	if string(after) != string(before) {
		t.Error("a refused import changed the configuration")
	}
}

// An ArrowLoop backup replaces the whole setup, so it goes through the
// restore, which asks about exactly that.
func TestAnArrowLoopBackupIsNamedNotAdded(t *testing.T) {
	h := newHarness(t)
	backup, _ := os.ReadFile(h.configPath)

	code, p, said := importing(t, h, "/api/import/check", string(backup))
	if code != http.StatusOK || p.Source != "ArrowLoop" || len(p.Jobs) != 0 {
		t.Errorf("check answered %d %s", code, said)
	}
	if code, _, _ := importing(t, h, "/api/import", string(backup)); code != http.StatusBadRequest {
		t.Errorf("importing a backup answered %d", code)
	}
}
